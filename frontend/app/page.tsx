"use client";
import MetricCard from "@/components/MetricCard";
import { ApiError, useApi } from "@/components/useApi";
import type { Card } from "@/lib/api";

const SECTIONS: { title: string; metrics: string[]; note?: string }[] = [
  { title: "HEADLINE — BIG-4 HYPERSCALER CAPEX (CALENDAR QUARTERS)", metrics: ["capex_total_big4_cal", "capex_total_big4_cal_yoy"],
    note: "MSFT+GOOGL+AMZN+META total company capex. Not AI-specific. ORCL excluded (non-calendar fiscal quarters)." },
  { title: "TOTAL COMPANY CAPEX (LATEST QUARTER)", metrics: ["capex_total"] },
  { title: "CAPEX YoY", metrics: ["capex_yoy"] },
  { title: "CAPEX / OPERATING CASH FLOW", metrics: ["capex_to_ocf"], note: ">1.0x = capex exceeds cash generated by operations in the quarter." },
  { title: "CAPEX / REVENUE", metrics: ["capex_to_revenue"] },
  { title: "FREE CASH FLOW (OCF − CAPEX)", metrics: ["fcf"] },
  { title: "REVENUE", metrics: ["revenue"] },
  { title: "MACRO", metrics: ["us10y_yield"] },
  { title: "NOT YET AVAILABLE (EXPLICIT GAPS)", metrics: ["nvda_datacenter_revenue", "ai_capex_disclosed", "market_cap"] },
];

export default function Overview() {
  const { data, error } = useApi<{ generated_at: string; cards: Card[] }>("/api/overview");
  if (error) return <ApiError error={error} />;
  if (!data) return <div className="font-mono text-term-muted">loading…</div>;
  return (
    <div className="space-y-5">
      <div className="flex items-end justify-between">
        <h1 className="font-mono text-term-amber text-lg">OVERVIEW · Does AI monetization justify the capex?</h1>
        <span className="text-[10px] font-mono text-term-muted">generated {data.generated_at}</span>
      </div>
      {SECTIONS.map((s) => {
        const cards = data.cards.filter((c) => s.metrics.includes(c.metric_id));
        return (
          <section key={s.title}>
            <div className="flex gap-3 items-baseline mb-1">
              <h2 className="font-mono text-xs text-term-amber">{s.title}</h2>
              {s.note ? <span className="text-[10px] text-term-muted">{s.note}</span> : null}
            </div>
            <div className="grid gap-2 grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-6">
              {cards.map((c) => <MetricCard key={c.metric_id + c.entity_id} c={c} />)}
            </div>
          </section>
        );
      })}
    </div>
  );
}
